package org.sonatype.nexus.blobstore.virtualthread;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

/**
 * Annotation for tests that should be run using virtual threads.
 * This is a composed annotation that includes both @Test and @Tag("virtualthread").
 *
 * @since 3.60
 */
@Target({ElementType.TYPE, ElementType.METHOD})
@Retention(RetentionPolicy.RUNTIME)
@Test
@Tag("virtualthread")
public @interface VirtualThreadTestGroup {
}