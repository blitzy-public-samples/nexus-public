  /**
   * Test that validation error messages use String Templates for variable interpolation.
   */
  @Test
  @DisplayName("Validation error messages use String Templates")
  void testValidationErrorMessages() {
    // Create a task with invalid configuration
    CompactBlobStoreTask task = new CompactBlobStoreTask(blobStoreManager, changeBlobstoreStore, 
        blobStoreUsageChecker, taskUtils) {
      @Override
      public void validate() {
        // Simulate validation with String Templates for error messages
        String fieldName = "blobStoreName";
        if (configuration.getString(fieldName) == null) {
          throw new IllegalArgumentException(STR."Missing required field: \{fieldName}");
        }
      }
    };
    
    // Create a configuration with missing required fields
    TaskConfiguration invalidConfig = new TaskConfiguration();
    invalidConfig.setString(".name", TASK_NAME);
    invalidConfig.setId(TASK_NAME);
    task.configure(invalidConfig);
    
    // Execute the test and verify the validation error message uses String Templates
    IllegalArgumentException exception = assertThrows(IllegalArgumentException.class, task::validate);
    
    // The expected message should use String Templates instead of concatenation or String.format
    // Original format might be: "Missing required field: " + fieldName
    // New format with String Templates: STR."Missing required field: \{fieldName}"
    String fieldName = "blobStoreName";
    String expectedMessage = STR."Missing required field: \{fieldName}";
    assertEquals(expectedMessage, exception.getMessage());
    
    // Verify the message doesn't use string concatenation
    String errorMessage = exception.getMessage();
    assertTrue(errorMessage.contains(fieldName), "Error message should contain the field name");
    assertTrue(!errorMessage.contains(" + "), "Error message should not use string concatenation");
  }
  
  /**
   * Test that user notification messages use String Templates for variable interpolation.
   */
  @Test
  @DisplayName("User notification messages use String Templates")
  void testUserNotificationMessages() {
    // Create a task that generates user notifications
    CompactBlobStoreTask task = new CompactBlobStoreTask(blobStoreManager, changeBlobstoreStore, 
        blobStoreUsageChecker, taskUtils) {
      @Override
      public String getMessage() {
        // Simulate the task's getMessage method using String Templates
        return STR."Compacting blob store '\{configuration.getString("blobStoreName")}'";
      }
    };
    task.configure(configuration);
    
    // Generate a user notification message
    String notificationMessage = task.getMessage();
    
    // The expected message should use String Templates instead of concatenation or String.format
    // Original format might be: "Compacting blob store '" + blobStoreName + "'"
    // New format with String Templates: STR."Compacting blob store '\{blobStoreName}'"
    String expectedMessage = STR."Compacting blob store '\{BLOBSTORE_NAME}'";
    assertEquals(expectedMessage, notificationMessage);
    
    // Verify the message contains the variable value and doesn't use concatenation
    assertTrue(notificationMessage.contains(BLOBSTORE_NAME), "Notification message should contain the blob store name");
    assertTrue(!notificationMessage.contains(" + "), "Notification message should not use string concatenation");
  }
  
  /**
   * Test that complex error messages with multiple variables use String Templates correctly.
   */
  @Test
  @DisplayName("Complex error messages with multiple variables use String Templates")
  void testComplexErrorMessagesWithMultipleVariables() {
    // Create a task that generates complex error messages
    CompactBlobStoreTask task = new CompactBlobStoreTask(blobStoreManager, changeBlobstoreStore, 
        blobStoreUsageChecker, taskUtils) {
      public String generateErrorMessage(String repositoryName, String errorType, int errorCode) {
        // Simulate a method that generates complex error messages using String Templates
        return STR."Error \{errorType} (code: \{errorCode}) occurred while compacting blob store '\{configuration.getString("blobStoreName")}' for repository '\{repositoryName}'";
      }
    };
    task.configure(configuration);
    
    // Set up a scenario that generates a complex error message with multiple variables
    String repositoryName = "maven-central";
    String errorType = "IO error";
    int errorCode = 500;
    
    // Generate a complex error message
    String errorMessage = task.generateErrorMessage(repositoryName, errorType, errorCode);
    
    // The expected message should use String Templates instead of concatenation or String.format
    // Original format might be: String.format("Error %s (code: %d) occurred while compacting blob store '%s' for repository '%s'", 
    //     errorType, errorCode, BLOBSTORE_NAME, repositoryName)
    // New format with String Templates: 
    // STR."Error \{errorType} (code: \{errorCode}) occurred while compacting blob store '\{BLOBSTORE_NAME}' for repository '\{repositoryName}'"
    String expectedMessage = STR."Error \{errorType} (code: \{errorCode}) occurred while compacting blob store '\{BLOBSTORE_NAME}' for repository '\{repositoryName}'";
    assertEquals(expectedMessage, errorMessage);
    
    // Verify the message contains all variable values and doesn't use String.format placeholders
    assertTrue(errorMessage.contains(errorType), "Error message should contain the error type");
    assertTrue(errorMessage.contains(String.valueOf(errorCode)), "Error message should contain the error code");
    assertTrue(errorMessage.contains(BLOBSTORE_NAME), "Error message should contain the blob store name");
    assertTrue(errorMessage.contains(repositoryName), "Error message should contain the repository name");
    assertTrue(!errorMessage.contains("%s") && !errorMessage.contains("%d"), 
        "Error message should not contain String.format placeholders");
  }
  
