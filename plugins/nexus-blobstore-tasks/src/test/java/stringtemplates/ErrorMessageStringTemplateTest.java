  /**
   * Test that multiline String Templates are correctly used in error messages.
   */
  @Test
  @DisplayName("Multiline String Templates in error messages")
  void testMultilineStringTemplatesInErrorMessages() {
    // Create a task that generates multiline error messages
    CompactBlobStoreTask task = new CompactBlobStoreTask(blobStoreManager, changeBlobstoreStore, 
        blobStoreUsageChecker, taskUtils) {
      public String generateMultilineErrorMessage(String repositoryName, String errorDetails) {
        // Simulate a method that generates multiline error messages using String Templates
        return STR."""
            Error occurred while processing blob store '\{configuration.getString("blobStoreName")}'
            Repository: \{repositoryName}
            Details: \{errorDetails}
            Please check the logs for more information.
            """;
      }
    };
    task.configure(configuration);
    
    // Set up a scenario that generates a multiline error message
    String repositoryName = "maven-central";
    String errorDetails = "Connection timeout";
    
    // Generate a multiline error message
    String errorMessage = task.generateMultilineErrorMessage(repositoryName, errorDetails);
    
    // The expected message should use multiline String Templates
    String expectedMessage = STR."""
            Error occurred while processing blob store '\{BLOBSTORE_NAME}'
            Repository: \{repositoryName}
            Details: \{errorDetails}
            Please check the logs for more information.
            """;
    assertEquals(expectedMessage, errorMessage);
    
    // Verify the message contains all variable values and is properly formatted
    assertTrue(errorMessage.contains(BLOBSTORE_NAME), "Error message should contain the blob store name");
    assertTrue(errorMessage.contains(repositoryName), "Error message should contain the repository name");
    assertTrue(errorMessage.contains(errorDetails), "Error message should contain the error details");
    assertTrue(errorMessage.contains("\n"), "Error message should contain newlines");
  }
